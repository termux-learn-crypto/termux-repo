class Node:
    _fields = ()
    def __init__(self, **kwargs):
        for k, v in kwargs.items():
            setattr(self, k, v)
    def __repr__(self):
        args = ", ".join(f"{k}={getattr(self, k, None)!r}" for k in self._fields)
        return f"{type(self).__name__}({args})"

def _mk(name, fields):
    return type(name, (Node,), {"_fields": tuple(fields)})

